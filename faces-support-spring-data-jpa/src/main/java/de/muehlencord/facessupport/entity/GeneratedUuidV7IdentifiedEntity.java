package de.muehlencord.facessupport.entity;

import com.fasterxml.jackson.annotation.JsonIdentityInfo;
import com.fasterxml.jackson.annotation.ObjectIdGenerators;
import jakarta.persistence.Basic;
import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.validation.constraints.NotNull;
import java.util.Objects;
import java.util.UUID;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.UuidGenerator;

/**
 * entity with id field of type UUID generated by database as uuidv7()
 *
 * @author Joern Muehlencord, 2026-10-18
 * @since 2.1.2
 */
@Setter
@Getter
@MappedSuperclass
@JsonIdentityInfo(generator = ObjectIdGenerators.PropertyGenerator.class, property = "id")
public abstract class GeneratedUuidV7IdentifiedEntity extends IdentifiableEntity<UUID> {

  /**
   * the id of the entity
   */
  @Id
  @Basic(optional = false)
  @NotNull
  @Column(name = "id")
  @GeneratedValue
  @UuidGenerator(style = UuidGenerator.Style.VERSION_7)
  protected UUID id;

  /**
   * generate the id based on {@link UUID#randomUUID()}.
   */
  @Override
  public void generateId() {
    if (id == null) {
      id = UUID.randomUUID();
    }
  }

  @Override
  public boolean equals(Object o) {
    var hibernateAwareEquals = super.hibernateAwareEquals(o);
    if (!hibernateAwareEquals) {
      return false;
    }

    if (o instanceof GeneratedUuidV7IdentifiedEntity that) {
      return Objects.equals(id, that.id);
    } else {
      return false;
    }
  }

}
